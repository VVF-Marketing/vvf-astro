#!/usr/bin/env node
// Regenerates docs-site/src/content/docs/design-tokens.md: colours from
// src/styles/tokens.cjs (their one source), everything else from the token
// comments in tailwind.config.cjs. Run after changing tokens:
//   node scripts/docs-tokens.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const SECTIONS = ['screens', 'fontFamily', 'fontSize', 'lineHeight', 'borderRadius', 'spacing', 'maxWidth']
const lines = readFileSync('tailwind.config.cjs', 'utf8').split('\n')
const rows = []
let section = ''
let group = ''
let temp = false
let groupTemp = false

for (const line of lines) {
  let m
  if ((m = line.match(/^ {4,6}(\w+): \{\s*$/))) {
    section = m[1]
    group = ''
    temp = groupTemp = false
    continue
  }
  if ((m = line.match(/^ {8}('?[\w-]+'?): \{\s*$/))) {
    group = m[1].replace(/'/g, '')
    groupTemp = false
    continue
  }
  if (/^ {8}\},?\s*(\/\/.*)?$/.test(line)) {
    group = ''
    groupTemp = false
    continue
  }
  if (/^\s*\/\/.*TEMPORARY/.test(line)) {
    if (group) groupTemp = true
    else temp = true
    continue
  }
  if (/^ {2}\w/.test(line)) section = ''
  if (!SECTIONS.includes(section)) continue
  if ((m = line.match(/^\s+('?[\w-]+'?|\d+): (\[[^\]]*\]|'[^']*'|\{[^}]*\})[^/]*(?:\/\/ (.*))?$/))) {
    const key = m[1].replace(/'/g, '')
    const nested = group && /^ {10}/.test(line)
    const name = nested ? `${group}-${key}` : key
    const value = m[2].replace(/[[\]{}']/g, '').replace(/\s+/g, ' ').trim()
    const comment = m[3] ?? ''
    const isTemp = (nested ? groupTemp : temp) || /TEMPORARY/.test(comment)
    rows.push({ section, name, value, source: isTemp ? '_temporary alias_' : comment })
  }
}

// Colours: `  name: '#hex', // comment` lines in tokens.cjs, comments
// continued on the lines above a token joined in.
const colorRows = []
let pending = []
for (const line of readFileSync('src/styles/tokens.cjs', 'utf8').split('\n')) {
  const m = line.match(/^\s+'?([\w-]+)'?: '(#[0-9a-f]{6})',?\s*(?:\/\/ (.*))?$/i)
  if (m) {
    colorRows.push({ name: m[1], value: m[2], source: [...pending, m[3] ?? ''].filter(Boolean).join(' ') })
    pending = []
  } else if (/^\s+\/\/ /.test(line)) pending.push(line.replace(/^\s+\/\/ /, ''))
  else pending = []
}

let md = `---
title: Design Tokens
description: Every design token, from src/styles/tokens.cjs and tailwind.config.cjs.
---

<!-- Generated by scripts/docs-tokens.mjs from src/styles/tokens.cjs and tailwind.config.cjs. Do not edit by hand. -->

Tokens follow the VVF website spec's design system (5.1 to 5.4). Colours have one source, \`src/styles/tokens.cjs\`: Tailwind's palette and the CSS variables (\`--navy\`, \`--blue-text\`, …) are built from it, and a unit test fails on any colour literal in a component, page, layout or stylesheet.

Font roles: Nunito for headings, buttons, body text and UI labels; Open Sans for taglines, labels and small text (spec 5.2).

## colors (src/styles/tokens.cjs)

| Token (CSS variable) | Value | Use |
| --- | --- | --- |
${colorRows.map((r) => `| \`--${r.name}\` | \`${r.value}\` | ${r.source.replace(/\|/g, '\\|')} |`).join('\n')}

Keyboard focus (Q12): \`--focus\` (\`blue\`) outlines the element and \`--focus-inner\` (\`navy\`) fills the 2 px gap inside it, from the one \`:focus-visible\` rule in \`src/index.css\`. Components don't set their own focus colours.
`
for (const s of SECTIONS.filter((s) => rows.some((r) => r.section === s))) {
  md += `\n## ${s}\n\n| Token | Value | Live variable / source |\n| --- | --- | --- |\n`
  for (const r of rows.filter((r) => r.section === s)) {
    md += `| \`${r.name}\` | \`${r.value.replace(/\|/g, '\\|')}\` | ${r.source.replace(/\|/g, '\\|')} |\n`
  }
}
writeFileSync('docs-site/src/content/docs/design-tokens.md', md)
console.log(`${rows.length} tokens written`)
